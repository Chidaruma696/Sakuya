# The only door for checking out and for refunds. Everything in one transaction: sale, lines,
# payments and kardex; if anything fails, nothing is left half done.
module Till
  class Error < StandardError; end

  # The price rule stopped a line: nothing is checked out and the attempt is reported.
  class Stopped < Error
    attr_reader :report, :value_cents

    def initialize(message, report:, value_cents:)
      super(message)
      @report = report
      @value_cents = value_cents
    end
  end

  # More returnable containers are coming back than the customer owes. Nothing is checked out and
  # nothing is reported (it is usually a typing mistake); `can_accept` says whether whoever checks
  # out may send it again accepting the surplus in the customer's favor.
  class MoreThanOwed < Error
    attr_reader :over, :can_accept

    def initialize(over, can_accept:)
      super(Returnables::MoreThanOwed.new(over).message)
      @over = over
      @can_accept = can_accept
    end
  end

  # lines:    [{ product_id:, quantity:, price_cents: }]
  # payments: [{ payment_method:, amount_cents: }]; the "credit" method goes on the customer's account.
  # key:      unique ticket identifier generated by the till; repeating the same key returns the same sale.
  # customer: who is buying (needed for selling on account).
  # order:    the order being checked out; what it reserved can be sold.
  # uploaded_by: who sent an offline sale to the server, when that is not who sold it (`user`).
  # sold_at:  if the sale was made offline and is uploaded now, when it was made. The goods already
  # left, so nothing is stopped: whatever a rule would have stopped (or reserved stock, or the cash
  # limit) is recorded and reported. Nothing is sold on account offline.
  # returnables: [{ kind:, out:, back: }], the returnable containers that leave with the sale and
  # come back with it, as the till counted them; accept_in_favor: whoever checks out accepts, with
  # returnables.in_favor, more pieces than the customer owes. An offline sale carries none.
  def self.checkout!(branch:, user:, lines:, payments:, key:, authorizer: nil, customer: nil, order: nil, sold_at: nil, uploaded_by: nil,
                     returnables: nil, accept_in_favor: false)
    raise Error, I18n.t("errors.till.key_ticket") if key.blank?
    if (existing = Sale.find_by(key: key))
      return existing
    end
    offline = sold_at.present?
    shift = Shift.opened_at(branch) or raise Error, I18n.t("errors.till.no_till", branch: branch.name)
    raise Error, I18n.t("errors.till.exceeds_limit", amount: Money.format_money(branch.cash_limit_cents)) if shift.exceeds_limit? && !offline
    raise Error, I18n.t("errors.till.ticket_empty") if lines.blank?

    code = Rule.current("price")&.code
    failures = [] # [text key, error] of the rules that blew up
    notices = [] # offline: what would have been stopped

    Sale.transaction do
      # Whoever else is charging this order or this customer's account waits for this one to finish.
      if order
        order.lock!
        raise Error, I18n.t("errors.order.not_open", folio: order.folio) unless order.open?
      end
      customer&.lock!
      prepared = lines.map { |l| prepare_line(branch, l, authorizer, code, failures, offline) }
      begin
        Reservations.check!(branch, prepared.map { |l| [ l[:product], l[:quantity] ] }, except: order)
      rescue Reservations::Error => e
        raise unless offline
        notices << e.message
      end
      total = prepared.sum { |l| l[:amount_cents] }
      payments_ok = prepare_payments(payments, total)
      change = payments_ok.sum { |p| p[:amount_cents] } - total
      on_account = payments_ok.select { |p| p[:payment_method] == Payment::ON_ACCOUNT }.sum { |p| p[:amount_cents] }
      raise Error, I18n.t("errors.till.on_account_offline") if offline && on_account.positive?
      review_sale = judge_sale!(prepared, payments_ok, total, change, user, failures, offline)
      review_credit = judge_credit!(customer, on_account, total, user, failures) if on_account.positive?
      pieces, review_returnables, value_returnables = offline ? [ [], nil, 0 ] : judge_returnables!(returnables, prepared, customer, user, failures, accept_in_favor)
      notices << I18n.t("till.offline_exceeds_limit") if offline && shift.exceeds_limit?
      review_sale = [ review_sale, *notices.map { |n| I18n.t("till.offline_notice", notice: n) } ].compact.join("\n").presence

      sale = Sale.create!(branch: branch, shift: shift, user: user, key: key, customer: customer,
                            folio: Folio.next_number!(branch, "sale"), code: ticket_code(branch),
                            total_cents: total, change_cents: change, business_date: (sold_at || Time.current).to_date,
                            offline: offline, sold_at: sold_at, uploaded_by: (uploaded_by if offline))
      prepared.each do |l|
        review, value = l.extract!(:review, :value_review).values_at(:review, :value_review)
        line = sale.lines.create!(l)
        Inventory.move!(branch: branch, product: line.product, kind: "sale", quantity: line.quantity,
                          user: user, reference: sale, reason: sale.folio)
        Review.open!(line, user: user, branch: branch, reason: review, value_cents: value) if review
      end
      payments_ok.each { |p| sale.payments.create!(p) }
      Review.open!(sale, user: user, branch: branch, reason: review_sale, value_cents: total) if review_sale
      if on_account.positive?
        customer.credit_movements.create!(kind: "charge", amount_cents: on_account, date: Date.current, reference: sale, branch: branch,
                                            user: user, reason: I18n.t("customers.account.charge_sale", folio: sale.folio))
        Review.open!(sale, user: user, branch: branch, reason: review_credit, value_cents: on_account) if review_credit
      end
      pieces.each do |p|
        Returnables.move!(customer, p[:kind], p[:out], "out", user: user, branch: branch, reference: sale) if p[:out].positive?
        Returnables.move!(customer, p[:kind], -p[:back], "back", user: user, branch: branch, reference: sale) if p[:back].positive?
      end
      Review.open!(sale, user: user, branch: branch, reason: review_returnables, value_cents: value_returnables) if review_returnables
      # If the business's rule blew up, the built-in one decided; the failure is reported once per shift.
      failures.uniq.each { |text_key, error| Review.open!(shift, user: user, branch: branch, reason: I18n.t(text_key, error: error), no_repeat: true) }
      # The order is delivered with its sale or not at all.
      order&.deliver!(sale)
      sale
    end
  rescue ActiveRecord::RecordNotUnique
    # The same ticket arrived twice at the same instant and the other one won: that is the sale.
    Sale.find_by(key: key) || raise
  rescue Inventory::OutOfStock, Reservations::Error => e
    raise Error, I18n.t("errors.till.cannot_sell_without", message: e.message)
  rescue Stopped => e
    Review.open!(shift, user: user, branch: branch, reason: e.report, value_cents: e.value_cents, stopped: true)
    raise
  end

  # lines: [{ sale_line_id:, quantity: }]. The money comes out of the open shift's drawer; if the
  # sale was on account, it first lowers what the customer owes on it and only the rest goes out in cash.
  # `key` is the form's idempotency key: the same key returns the same refund.
  def self.refund!(sale:, lines:, reason:, user:, key: nil)
    if key.present? && (previous = Refund.find_by(key: key))
      return previous
    end
    raise Error, I18n.t("errors.reason_required") if reason.blank?
    raise Error, I18n.t("errors.till.already_refunded") unless sale.paid?
    shift = Shift.opened_at(sale.branch) or raise Error, I18n.t("errors.till.no_till_refund")
    raise Error, I18n.t("errors.till.nothing_refunded") if lines.blank?

    Sale.transaction do
      sale.lock! # two refunds of the same ticket go one after the other, each seeing what the other took
      refund = Refund.new(sale: sale, shift: shift, user: user, reason: reason, total_cents: 0, key: key.presence)
      total = 0
      lines.each do |l|
        sale_line = sale.lines.find(l[:sale_line_id])
        product = sale_line.product
        quantity = quantity!(l[:quantity], product)
        raise Error, I18n.t("errors.till.max_refund", product: product.name, max: sale_line.pending_quantity.to_s("F")) if quantity > sale_line.pending_quantity
        # Whatever closes the line takes what is left of it, cent for cent: refunding a line in
        # parts never adds up to more (or less) than what was charged for it.
        left = sale_line.amount_cents - sale_line.refund_lines.sum(:amount_cents)
        amount = quantity == sale_line.pending_quantity ? left : [ Money.amount(quantity, sale_line.price_cents), left ].min
        total += amount
        refund.lines.build(sale_line: sale_line, quantity: quantity, amount_cents: amount)
        Inventory.move!(branch: sale.branch, product: product, kind: "customer_return", quantity: quantity,
                          user: user, reference: refund, reason: "#{sale.folio}: #{reason}")
      end
      refund.total_cents = total
      refund.on_account_cents = [ total, sale.on_account_pending_cents ].min if sale.customer
      refund.save!
      if refund.on_account_cents.positive?
        sale.customer.credit_movements.create!(kind: "refund", amount_cents: -refund.on_account_cents, date: Date.current, reference: refund,
                                                  branch: sale.branch, user: user, reason: I18n.t("customers.account.refund", folio: sale.folio))
      end
      sale.update!(status: "refunded") if sale.lines.all? { |sl| sl.reload.pending_quantity.zero? }
      refund
    end
  end

  def self.prepare_line(branch, l, authorizer, code, failures, offline = false)
    product = Product.active.find(l[:product_id])
    quantity = quantity!(l[:quantity], product)
    catalog = product.price_cents_for(branch)
    # A new product reaches the store without a price: it can be received, but not sold until it has one.
    raise Error, I18n.t("errors.till.no_price", product: product.name, branch: branch.name) unless catalog.positive?
    promo_price, promotion = Promotion.best(product, branch, quantity, catalog)
    regular = promo_price || catalog
    price = l[:price_cents].present? ? l[:price_cents].to_i : regular
    if price < regular
      floor = Setting.integer("till.price_floor") # never below the floor, not with permission nor with a rule
      lowest = Rational(catalog * floor, 100).ceil # in whole cents, no floats: the floor itself can always be charged
      raise Error, I18n.t("errors.till.price_floor", product: product.name, floor: floor, amount: Money.format_money(lowest)) if price < lowest
    end
    # The price rule decides the rest. If it stops and whoever authorizes has till.lower_price, it
    # goes through under their name but stays pending review: nobody is left unable to sell.
    authorized = authorizer&.can?("till.lower_price") || false
    data = PriceRule::Input.new(product: product, quantity: quantity, price: price, catalog: catalog, regular: regular, authorized: authorized)
    decision = PriceRule.decide(data, code: code)
    failures << [ "price_rule.failure", decision.error ] if decision.error
    line_text = I18n.t("till.price_line", product: product.name, price: Money.format_money(price), regular: Money.format_money(regular))
    value = Money.amount(quantity, [ regular - price, 0 ].max)
    if decision.rejects? && !authorized && !offline
      raise Stopped.new(I18n.t("errors.till.price_stopped", line: line_text, reason: decision.reason), report: "#{line_text}: #{decision.reason}", value_cents: value)
    end
    offline_would_stop = decision.rejects? && !authorized
    { product: product, quantity: quantity, price_cents: price, catalog_cents: catalog,
      amount_cents: Money.amount(quantity, price), authorized_by: (authorizer if authorized && price < regular),
      promotion: (price == promo_price ? promotion : nil),
      review: (decision.allows? ? nil : (offline_would_stop ? I18n.t("till.offline_notice", notice: "#{line_text}: #{decision.reason}") : "#{line_text}: #{decision.reason}")),
      value_review: value }
  end
  private_class_method :prepare_line

  # A quantity as it comes from the screen: a positive number the kardex can hold (three decimals),
  # whole if the product is sold by the piece. Anything else is refused by name, not with a crash.
  MAX_QUANTITY = 999_999_999

  def self.quantity!(value, product)
    quantity = begin
      BigDecimal(value.to_s)
    rescue ArgumentError
      nil
    end
    raise Error, I18n.t("errors.till.invalid_quantity", product: product.name) unless quantity&.finite? && quantity.round(3).positive? && quantity <= MAX_QUANTITY
    quantity = quantity.round(3)
    raise Error, I18n.t("errors.till.whole_pieces", product: product.name) if !product.fractional? && quantity != quantity.floor
    quantity
  end
  private_class_method :quantity!

  # The whole sale, before checking it out, through the sales rule. If it stops and whoever checks
  # out does not have till.force_sale, it is not checked out and gets reported; otherwise returns
  # the reason to review it (or nil).
  def self.judge_sale!(prepared, payments, total, change, user, failures, offline = false)
    authorized = user.can?("till.force_sale")
    data = SaleRule.data(prepared, payments, total: total, change: change, authorized: authorized)
    decision = SaleRule.decide(data, code: Rule.current("sale")&.code)
    failures << [ "sale_rule.failure", decision.error ] if decision.error
    if decision.rejects? && !authorized
      return I18n.t("till.offline_notice", notice: decision.reason) if offline
      raise Stopped.new(I18n.t("errors.till.sale_stopped", reason: decision.reason), report: I18n.t("till.sale_stopped", total: Money.format_money(total), reason: decision.reason), value_cents: total)
    end
    decision.allows? ? nil : decision.reason
  end
  private_class_method :judge_sale!

  # On the customer's account, if the credit rule allows it. If it stops and whoever checks out
  # does not have customers.force_credit, it is not checked out and gets reported; otherwise returns
  # the reason to review it (or nil).
  def self.judge_credit!(customer, on_account, total, user, failures)
    raise Error, I18n.t("errors.till.on_account_no_customer") unless customer
    authorized = user.can?("customers.force_credit")
    decision = CreditRule.decide(CreditRule.data(customer, amount: on_account, total: total, authorized: authorized))
    failures << [ "credit_rule.failure", decision.error ] if decision.error
    if decision.rejects? && !authorized
      raise Stopped.new(I18n.t("errors.till.credit_stopped", reason: decision.reason),
                        report: I18n.t("till.credit_stopped", customer: customer.name, amount: Money.format_money(on_account), reason: decision.reason), value_cents: on_account)
    end
    decision.allows? ? nil : decision.reason
  end
  private_class_method :judge_credit!

  # The returnable containers of a sale: what its products release (each line counted on its own)
  # against what the till typed. Pieces need a customer; more coming back than owed is stopped
  # unless accepted with returnables.in_favor; each kind leaving is judged by its own rule, and a
  # rejection stops the whole sale unless whoever checks out has returnables.force. Returns
  # [[{ kind:, out:, back: }], the reason to review the sale (or nil), what that is worth].
  def self.judge_returnables!(typed, prepared, customer, user, failures, accept_in_favor)
    kinds = Features.active?("returnables") ? ReturnableRule.kinds : {}
    return [ [], nil, 0 ] if kinds.empty?
    expected = Returnables.released(prepared.map { |l| [ l[:product], l[:quantity] ] }, kinds)
    typed = Array(typed).to_h { |r| [ r[:kind].to_s, [ Returnables.pieces!(r[:out]), Returnables.pieces!(r[:back]) ] ] }
    moving = (typed.keys | expected.keys).filter_map do |kind|
      out, back = typed.fetch(kind, [ 0, 0 ])
      next if out.zero? && back.zero? && expected[kind].zero?
      raise Error, I18n.t("returnables.errors.undeclared", kind: kind) unless kinds.key?(kind)
      { kind: kind, out: out, back: back, expected: expected[kind] }
    end
    return [ [], nil, 0 ] if moving.empty?
    raise Error, I18n.t("errors.till.returnables_no_customer") unless customer

    account = customer.returnable_account
    over = moving.select { |m| m[:back] > account.owed(m[:kind]) }
    can_accept = user.can?("returnables.in_favor")
    if over.any? && !(accept_in_favor && can_accept)
      raise MoreThanOwed.new(over.map { |m| { kind: m[:kind], name: kinds[m[:kind]].name, owed: account.owed(m[:kind]), back: m[:back] } }, can_accept: can_accept)
    end

    authorized = user.can?("returnables.force")
    reviews = []
    value = 0
    moving.each do |m|
      kind = kinds[m[:kind]]
      worth = kind.value_cents.to_i
      if m[:out].positive?
        decision = ReturnableRule.decide(ReturnableRule.data(customer, kind: kind.key, name: kind.name, leaving: m[:out], returning: m[:back], authorized: authorized))
        failures << [ "returnable_rule.failure", decision.error ] if decision.error
        line = I18n.t("till.returnable_line", kind: kind.name, pieces: m[:out], customer: customer.name)
        if decision.rejects? && !authorized
          raise Stopped.new(I18n.t("errors.till.returnable_stopped", kind: kind.name, reason: decision.reason), report: "#{line}: #{decision.reason}", value_cents: worth * m[:out])
        end
        unless decision.allows?
          reviews << "#{line}: #{decision.reason}"
          value += worth * m[:out]
        end
      end
      # The till proposes what the products release; letting fewer pieces go is allowed and looked at.
      if m[:out] < m[:expected]
        reviews << I18n.t("till.returnable_fewer", kind: kind.name, pieces: m[:out], expected: m[:expected])
        value += worth * (m[:expected] - m[:out])
      end
      surplus = m[:back] - account.owed(m[:kind])
      reviews << I18n.t("returnables.review.in_favor", kind: kind.name, pieces: surplus, customer: customer.name) if surplus.positive?
    end
    [ moving, reviews.join("\n").presence, value ]
  rescue Returnables::Error => e
    raise Error, e.message
  end
  private_class_method :judge_returnables!

  def self.prepare_payments(payments, total)
    clean = Array(payments).map { |p| { payment_method: p[:payment_method].to_s, amount_cents: p[:amount_cents].to_i } }.reject { |p| p[:amount_cents] <= 0 }
    clean.each { |p| raise Error, I18n.t("errors.till.unknown_payment_method", payment_method: p[:payment_method]) unless (Payment::PAYMENT_METHODS + [ Payment::ON_ACCOUNT ]).include?(p[:payment_method]) }
    sum = clean.sum { |p| p[:amount_cents] }
    raise Error, I18n.t("errors.till.missing_money", total: Money.format_money(total), payment: Money.format_money(sum)) if sum < total
    non_cash = clean.reject { |p| p[:payment_method] == "cash" }.sum { |p| p[:amount_cents] }
    raise Error, I18n.t("errors.till.non_cash_exceeds") if non_cash > total
    clean
  end
  private_class_method :prepare_payments

  def self.ticket_code(branch)
    sequence = Counter.next_number!("ticket:#{branch.id}")
    Barcode.ean13(format("09%02d%08d", branch.id % 100, sequence % 100_000_000))
  end
  private_class_method :ticket_code
end
